import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const distDir = path.resolve(__dirname, '../dist')
const laravelPublicDir = path.resolve(__dirname, '../../public')

if (!fs.existsSync(distDir)) {
  console.error('[publish] dist/ folder does not exist. Run vite build first.')
  process.exit(1)
}

function copyRecursiveSync(src, dest) {
  const exists = fs.existsSync(src)
  const stats = exists && fs.statSync(src)
  const isDirectory = exists && stats.isDirectory()

  if (isDirectory) {
    if (!fs.existsSync(dest)) {
      fs.mkdirSync(dest, { recursive: true })
    }
    fs.readdirSync(src).forEach((childItemName) => {
      copyRecursiveSync(path.join(src, childItemName), path.join(dest, childItemName))
    })
  } else {
    fs.copyFileSync(src, dest)
  }
}

// Stale hashed assets from previous builds must not survive a publish:
// the service worker is cache-first for static assets, and an old index-*.js
// lying next to the new one lets the SW keep serving yesterday's app.
const EXCLUDE_AFTER_COPY = []
for (const item of fs.readdirSync(laravelPublicDir)) {
  if (item === 'assets' || item === 'map') continue
  // (kept for clarity: only assets/map dirs hold build output)
}
if (fs.existsSync(path.join(laravelPublicDir, 'assets'))) {
  fs.rmSync(path.join(laravelPublicDir, 'assets'), { recursive: true })
}
if (fs.existsSync(path.join(laravelPublicDir, 'map'))) {
  // map/ holds the synced maplibre worker — regenerated by sync script, but
  // stale copies break nothing; clean it too for a deterministic publish.
  fs.rmSync(path.join(laravelPublicDir, 'map'), { recursive: true })
}

const itemsToCopy = fs.readdirSync(distDir)

for (const item of itemsToCopy) {
  const srcPath = path.join(distDir, item)
  const destPath = path.join(laravelPublicDir, item)
  // Protect critical backend files if any
  if (item === '.htaccess' || item === 'index.php' || item === 'robots.txt') {
    continue
  }
  copyRecursiveSync(srcPath, destPath)
}

console.log(`[publish] Successfully published frontend build to ${laravelPublicDir}`)
